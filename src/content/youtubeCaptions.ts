import type {
  CaptionBridgePayload,
  CaptionTrack,
  SubtitleCue,
} from "../core/types";

export type TrackSelection =
  | { kind: "already-turkish"; track: CaptionTrack }
  | { kind: "translate"; track: CaptionTrack }
  | { kind: "none" };

function isTurkish(languageCode: string): boolean {
  const code = languageCode.toLowerCase();
  return code === "tr" || code.startsWith("tr-");
}

function isEnglish(languageCode: string): boolean {
  const code = languageCode.toLowerCase();
  return code === "en" || code.startsWith("en-");
}

export function selectCaptionTrack(tracks: CaptionTrack[]): TrackSelection {
  const turkishTrack = tracks.find((track) =>
    isTurkish(track.languageCode),
  );

  if (turkishTrack) {
    return { kind: "already-turkish", track: turkishTrack };
  }

  const ranked = [...tracks].sort((left, right) => {
    const score = (track: CaptionTrack) => {
      if (isEnglish(track.languageCode) && !track.isAutoGenerated) return 0;
      if (isEnglish(track.languageCode) && track.isAutoGenerated) return 1;
      if (!track.isAutoGenerated) return 2;
      return 3;
    };
    return score(left) - score(right);
  });

  return ranked[0]
    ? { kind: "translate", track: ranked[0] }
    : { kind: "none" };
}

export function requestCaptionTracks(
  expectedVideoId: string,
  timeoutMs = 6_000,
): Promise<CaptionBridgePayload> {
  return new Promise((resolve, reject) => {
    let lastPayload: CaptionBridgePayload | null = null;
    let settleId: number | null = null;
    const combinedTracks = new Map<string, CaptionTrack>();
    const finish = (payload: CaptionBridgePayload) => {
      window.clearTimeout(timeoutId);
      if (settleId != null) window.clearTimeout(settleId);
      window.removeEventListener("message", handleMessage);
      resolve(payload);
    };
    const timeoutId = window.setTimeout(() => {
      window.removeEventListener("message", handleMessage);
      if (settleId != null) window.clearTimeout(settleId);
      if (lastPayload) resolve(lastPayload);
      else reject(new Error("YouTube altyazı bilgisi zamanında alınamadı."));
    }, timeoutMs);

    function handleMessage(event: MessageEvent) {
      if (
        event.source !== window || event.origin !== location.origin ||
        event.data?.source !== "smart-subtitles-page" ||
        event.data?.type !== "CAPTION_TRACKS"
      ) {
        return;
      }

      const payload = event.data.payload as CaptionBridgePayload;
      if (!payload || payload.videoId !== expectedVideoId || !Array.isArray(payload.tracks) ||
        payload.tracks.length > 100 || !payload.tracks.every((track) => track &&
          typeof track.id === "string" && typeof track.name === "string" &&
          typeof track.languageCode === "string" && typeof track.url === "string" &&
          typeof track.isAutoGenerated === "boolean")) return;
      for (const track of payload.tracks) {
        combinedTracks.set(
          `${track.languageCode}:${track.isAutoGenerated ? "auto" : "manual"}`,
          track,
        );
      }
      lastPayload = { ...payload, tracks: [...combinedTracks.values()] };
      if (payload.tracks.length === 0) return;

      if (
        payload.transport === "android" ||
        lastPayload.tracks.some((track) => isTurkish(track.languageCode))
      ) {
        finish(lastPayload);
        return;
      }

      if (settleId == null) {
        settleId = window.setTimeout(() => {
          if (lastPayload) finish(lastPayload);
        }, 700);
      }
    }

    window.addEventListener("message", handleMessage);
    window.postMessage(
      {
        source: "smart-subtitles-extension",
        type: "REQUEST_CAPTION_TRACKS",
        payload: { videoId: expectedVideoId },
      },
      location.origin,
    );
  });
}

export function requestCaptionPayload(
  track: CaptionTrack,
  videoId: string,
  timeoutMs = 20_000,
): Promise<{ cues: SubtitleCue[]; transport: "page-web" | "page-android" }> {
  return new Promise((resolve, reject) => {
    const requestId = crypto.randomUUID();
    const timeoutId = window.setTimeout(() => {
      window.removeEventListener("message", handleMessage);
      reject(new Error("Sayfa caption isteği zaman aşımına uğradı."));
    }, timeoutMs);

    function handleMessage(event: MessageEvent) {
      if (
        event.source !== window || event.origin !== location.origin ||
        event.data?.source !== "smart-subtitles-page" ||
        event.data?.type !== "CAPTION_PAYLOAD" ||
        event.data?.requestId !== requestId
      ) {
        return;
      }

      window.clearTimeout(timeoutId);
      window.removeEventListener("message", handleMessage);
      if (!event.data.ok) {
        reject(new Error(event.data.error || "Sayfa caption isteği başarısız."));
        return;
      }
      const cues = event.data.cues as SubtitleCue[];
      if (!Array.isArray(cues) || cues.length > 100_000 || !cues.every((cue) => cue &&
        Number.isSafeInteger(cue.id) && cue.id >= 0 && typeof cue.text === "string" &&
        Number.isFinite(cue.start) && cue.start >= 0 && Number.isFinite(cue.duration) &&
        cue.duration > 0 && Number.isFinite(cue.end) && cue.end > cue.start) ||
        !["page-web", "page-android"].includes(event.data.transport)) {
        reject(new Error("Geçersiz altyazı yanıtı."));
        return;
      }
      resolve({ cues, transport: event.data.transport });
    }

    window.addEventListener("message", handleMessage);
    window.postMessage(
      {
        source: "smart-subtitles-extension",
        type: "REQUEST_CAPTION_PAYLOAD",
        payload: {
          requestId,
          trackUrl: track.url,
          videoId,
          languageCode: track.languageCode,
          isAutoGenerated: track.isAutoGenerated,
        },
      },
      location.origin,
    );
  });
}

type RawCaptionTrack = {
  baseUrl?: string;
  languageCode?: string;
  vssId?: string;
  kind?: string;
  isTranslatable?: boolean;
  name?: { simpleText?: string; runs?: Array<{ text?: string }> };
};

export {};

type PlayerResponse = {
  videoDetails?: { videoId?: string };
  captions?: {
    playerCaptionsTracklistRenderer?: { captionTracks?: RawCaptionTrack[] };
  };
};

declare global {
  interface Window {
    ytInitialPlayerResponse?: PlayerResponse;
    ytcfg?: { get?: (key: string) => unknown };
    __smartSubtitlesPageBridgeLoaded?: boolean;
    __smartSubtitlesPageBridgeRuntime?: {
      version: string;
      dispose: () => void;
    };
  }
}

type CaptionPayloadRequest = {
  requestId: string;
  trackUrl: string;
  videoId: string;
  languageCode: string;
  isAutoGenerated: boolean;
};

function currentVideoId(): string | null {
  const url = new URL(location.href);
  const candidate =
    url.pathname === "/watch"
      ? url.searchParams.get("v")
      : url.pathname.match(/^\/(?:shorts|live|embed)\/([^/?#]+)/)?.[1];
  return candidate && /^[a-zA-Z0-9_-]{11}$/.test(candidate)
    ? candidate
    : null;
}

function readPlayerResponse(): PlayerResponse | null {
  const player = document.getElementById("movie_player") as
    | (HTMLElement & { getPlayerResponse?: () => PlayerResponse })
    | null;

  try {
    return player?.getPlayerResponse?.() ?? window.ytInitialPlayerResponse ?? null;
  } catch {
    return window.ytInitialPlayerResponse ?? null;
  }
}

function trackName(track: RawCaptionTrack): string {
  return (
    track.name?.simpleText ??
    track.name?.runs?.map((run) => run.text ?? "").join("") ??
    track.languageCode ??
    "Bilinmeyen dil"
  );
}

function normalizeTracks(rawTracks: RawCaptionTrack[]) {
  return rawTracks
    .filter((track) => track.baseUrl && track.languageCode)
    .map((track, index) => ({
      id:
        track.vssId ??
        `${track.languageCode}:${track.kind === "asr" ? "asr" : "manual"}:${index}`,
      name: trackName(track),
      languageCode: track.languageCode!,
      isAutoGenerated:
        track.kind === "asr" || Boolean(track.vssId?.startsWith("a.")),
      isTranslatable: track.isTranslatable !== false,
      url: track.baseUrl!,
    }));
}

function postTracks(
  videoId: string,
  rawTracks: RawCaptionTrack[],
  transport: "player" | "android",
) {
  window.postMessage(
    {
      source: "smart-subtitles-page",
      type: "CAPTION_TRACKS",
      payload: { videoId, tracks: normalizeTracks(rawTracks), transport },
    },
    location.origin,
  );
}

function postVideoContext(videoId: string) {
  window.postMessage(
    {
      source: "smart-subtitles-page",
      type: "VIDEO_CONTEXT",
      payload: { videoId },
    },
    location.origin,
  );
}

let previousSignature = "";

function publishTracks(force = false) {
  const response = readPlayerResponse();
  const videoId = response?.videoDetails?.videoId ?? currentVideoId();
  const rawTracks =
    response?.captions?.playerCaptionsTracklistRenderer?.captionTracks ?? [];

  if (!videoId) return;

  postVideoContext(videoId);

  const tracks = normalizeTracks(rawTracks);

  const signature = `${videoId}:${tracks.map((track) => track.id).join("|")}`;
  if (!force && signature === previousSignature) return;
  previousSignature = signature;

  postTracks(videoId, rawTracks, "player");
}

function isAllowedTimedTextUrl(urlString: string): boolean {
  try {
    const url = new URL(urlString);
    return url.protocol === "https:" && !url.username && !url.password &&
      (!url.port || url.port === "443") &&
      (url.hostname === "youtube.com" || url.hostname.endsWith(".youtube.com")) &&
      url.pathname === "/api/timedtext";
  } catch {
    return false;
  }
}

async function fetchTimedText(
  urlString: string,
  credentials: RequestCredentials,
): Promise<string> {
  if (!isAllowedTimedTextUrl(urlString)) {
    throw new Error("Geçersiz timed-text URL'si.");
  }
  const url = new URL(urlString);
  url.searchParams.set("fmt", "json3");
  const response = await fetch(url, { credentials, redirect: "error" });
  if (!response.ok) {
    throw new Error(`Timed-text isteği başarısız (${response.status}).`);
  }
  const payload = await response.text();
  if (!payload.trim()) throw new Error("Timed-text yanıtı boş.");
  return payload;
}

async function fetchAndroidPlayerResponse(
  videoId: string,
): Promise<PlayerResponse> {
  const apiKey = window.ytcfg?.get?.("INNERTUBE_API_KEY");
  if (typeof apiKey !== "string" || !apiKey) {
    throw new Error("Sayfa Innertube API anahtarı bulunamadı.");
  }

  const playerResponse = await fetch(
    `/youtubei/v1/player?key=${encodeURIComponent(apiKey)}`,
    {
      method: "POST",
      credentials: "omit",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({
        context: {
          client: { clientName: "ANDROID", clientVersion: "20.10.38" },
        },
        videoId,
      }),
    },
  );
  if (!playerResponse.ok) {
    throw new Error(`Sayfa Android player isteği başarısız (${playerResponse.status}).`);
  }
  return (await playerResponse.json()) as PlayerResponse;
}

async function publishAndroidTracks(videoId: string) {
  const player = await fetchAndroidPlayerResponse(videoId);
  const tracks =
    player.captions?.playerCaptionsTracklistRenderer?.captionTracks ?? [];
  postTracks(videoId, tracks, "android");
}

type Json3Event = {
  tStartMs?: number;
  dDurationMs?: number;
  segs?: Array<{ utf8?: string; tOffsetMs?: number }>;
};

type SubtitleCue = { id: number; start: number; duration: number; end: number; text: string };

function normalizeText(text: string): string {
  return text.replace(/\s+/g, " ").trim();
}

function decodeEntities(text: string): string {
  const entities: Record<string, string> = {
    amp: "&",
    lt: "<",
    gt: ">",
    quot: '"',
    apos: "'",
    "#39": "'",
  };

  return text
    .replace(/<[^>]+>/g, "")
    .replace(/&(#x?[0-9a-f]+|[a-z]+);/gi, (match, entity: string) => {
      if (entity.startsWith("#")) {
        const hex = entity.slice(0, 2).toLowerCase() === "#x";
        const code = Number.parseInt(entity.slice(hex ? 2 : 1), hex ? 16 : 10);
        return Number.isInteger(code) && code >= 0 && code <= 0x10ffff
          ? String.fromCodePoint(code) : match;
      }
      return entities[entity.toLowerCase()] ?? match;
    });
}

function finalizeCues(
  cues: Array<Omit<SubtitleCue, "id" | "end"> & { end?: number }>,
): SubtitleCue[] {
  const normalized = cues
    .map((cue) => ({ ...cue, text: normalizeText(decodeEntities(cue.text)) }))
    .filter((cue) => cue.text && Number.isFinite(cue.start) && cue.start >= 0 && Number.isFinite(cue.duration))
    .sort((left, right) => left.start - right.start);
  return normalized
    .map((cue, index, all) => {
      const inferredDuration = Math.max(
        0.35,
        Math.min(4, (all[index + 1]?.start ?? cue.start + 4) - cue.start),
      );
      const duration = cue.duration > 0 ? cue.duration : inferredDuration;
      return {
        id: index,
        start: cue.start,
        duration,
        end: cue.end ?? cue.start + duration,
        text: cue.text,
      };
    })
    .filter((cue) => cue.text.length > 0);
}

function parseJson3Payload(payload: string): SubtitleCue[] {
  const parsed = JSON.parse(payload) as { events?: Json3Event[] };
  const cues = (parsed.events ?? []).flatMap((event) => {
    const start = (event.tStartMs ?? 0) / 1_000;
    const duration = (event.dDurationMs ?? 0) / 1_000;
    const segments = event.segs ?? [];
    if (!segments.some((segment) => (segment.tOffsetMs ?? 0) > 0)) {
      return [{ start, duration, text: segments.map((segment) => segment.utf8 ?? "").join("") }];
    }

    const groups: Array<{ offset: number; text: string }> = [];
    let lastOffset = 0;
    for (const segment of segments) {
      lastOffset = Math.max(lastOffset, Math.max(0, segment.tOffsetMs ?? lastOffset));
      const text = segment.utf8 ?? "";
      if (!text.trim()) {
        if (groups.length) groups[groups.length - 1].text += text;
        continue;
      }
      const group = groups[groups.length - 1];
      if (!group || lastOffset - group.offset >= 2_500) {
        groups.push({ offset: lastOffset, text });
      } else {
        group.text += text;
      }
    }
    return groups.map((group, index) => ({
      start: start + group.offset / 1_000,
      duration: groups[index + 1]?.offset !== undefined
        ? Math.min(4, (groups[index + 1].offset - group.offset) / 1_000)
        : duration > 0 ? Math.min(4, Math.max(0.35, duration - group.offset / 1_000)) : 0,
      text: group.text,
    }));
  });
  return finalizeCues(cues);
}

async function fetchCaptionPayload(request: CaptionPayloadRequest) {
  if (!/^[a-zA-Z0-9_-]{11}$/.test(request.videoId)) {
    throw new Error("Geçersiz video ID.");
  }

  try {
    const payload = await fetchTimedText(request.trackUrl, "include");
    return { cues: parseJson3Payload(payload), transport: "page-web" };
  } catch {
    const player = await fetchAndroidPlayerResponse(request.videoId);
    const tracks =
      player.captions?.playerCaptionsTracklistRenderer?.captionTracks ?? [];
    const fallback =
      tracks.find(
        (track) =>
          track.languageCode === request.languageCode &&
          (track.kind === "asr") === request.isAutoGenerated,
      ) ?? tracks.find((track) => track.languageCode === request.languageCode);
    if (!fallback?.baseUrl) {
      throw new Error("Sayfa Android fallback track'i bulunamadı.");
    }

    const payload = await fetchTimedText(fallback.baseUrl, "omit");
    return { cues: parseJson3Payload(payload), transport: "page-android" };
  }
}

function handleBridgeMessage(event: MessageEvent) {
  if (
    event.source !== window || event.origin !== location.origin ||
    event.data?.source !== "smart-subtitles-extension"
  ) {
    return;
  }

  if (event.data?.type === "REQUEST_CAPTION_TRACKS") {
    publishTracks(true);
    const requestedVideoId = event.data.payload?.videoId;
    if (
      typeof requestedVideoId === "string" &&
      /^[a-zA-Z0-9_-]{11}$/.test(requestedVideoId)
    ) {
      void publishAndroidTracks(requestedVideoId).catch(() => undefined);
    }
    return;
  }

  if (event.data?.type === "REQUEST_CAPTION_PAYLOAD") {
    const request = event.data.payload as CaptionPayloadRequest;
    if (!request || typeof request.requestId !== "string" || request.requestId.length > 100 ||
      typeof request.videoId !== "string" || !/^[a-zA-Z0-9_-]{11}$/.test(request.videoId) ||
      typeof request.trackUrl !== "string" || !isAllowedTimedTextUrl(request.trackUrl) ||
      typeof request.languageCode !== "string" || typeof request.isAutoGenerated !== "boolean") return;
    void fetchCaptionPayload(request)
      .then((result) => {
        window.postMessage(
          {
            source: "smart-subtitles-page",
            type: "CAPTION_PAYLOAD",
            requestId: request.requestId,
            ok: true,
            ...result,
          },
          location.origin,
        );
      })
      .catch((error: unknown) => {
        window.postMessage(
          {
            source: "smart-subtitles-page",
            type: "CAPTION_PAYLOAD",
            requestId: request.requestId,
            ok: false,
            error: error instanceof Error ? error.message : "Sayfa caption isteği başarısız.",
          },
          location.origin,
        );
      });
  }
}

function handleYouTubeNavigation() {
  previousSignature = "";
  window.setTimeout(() => publishTracks(true), 100);
}

window.__smartSubtitlesPageBridgeRuntime?.dispose();
window.__smartSubtitlesPageBridgeLoaded = true;
window.addEventListener("message", handleBridgeMessage);
window.addEventListener("yt-navigate-finish", handleYouTubeNavigation);
const bridgeIntervalId = window.setInterval(() => publishTracks(false), 750);
publishTracks(true);

window.__smartSubtitlesPageBridgeRuntime = {
  version: "1.20.5",
  dispose: () => {
    window.clearInterval(bridgeIntervalId);
    window.removeEventListener("message", handleBridgeMessage);
    window.removeEventListener("yt-navigate-finish", handleYouTubeNavigation);
  },
};

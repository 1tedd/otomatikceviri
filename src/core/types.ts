export type SubtitleCue = {
  id: number;
  start: number;
  duration: number;
  end: number;
  text: string;
};

export type VideoState = {
  videoId: string | null;
  url: string;
  detectedAt: number;
};

export type TranslatedSubtitleCue = SubtitleCue & {
  translatedText: string;
};

export type CaptionTrack = {
  id: string;
  name: string;
  languageCode: string;
  isAutoGenerated: boolean;
  isTranslatable: boolean;
  url: string;
};

export type SubtitleMode = "translated" | "dual";

export type SubtitleSettings = {
  enabled: boolean;
  mode: SubtitleMode;
  fontSize: number;
  position: number;
  background: boolean;
};

export type ExtensionStatus =
  | "idle"
  | "detecting"
  | "loading-captions"
  | "translating"
  | "ready"
  | "already-turkish"
  | "no-video"
  | "no-tracks"
  | "error";

export type ExtensionState = {
  videoId: string | null;
  url: string;
  detectedAt: number;
  status: ExtensionStatus;
  sourceLanguage: string | null;
  sourceLabel: string | null;
  sourceTrackId: string | null;
  hasManualTurkish: boolean;
  progress: number;
  total: number;
  error: string | null;
  settings: SubtitleSettings;
};

export type TranslationCache = {
  videoId: string;
  sourceLanguage: string;
  targetLanguage: "tr";
  trackId: string;
  createdAt: number;
  cues: TranslatedSubtitleCue[];
};

export type CaptionBridgePayload = {
  videoId: string | null;
  tracks: CaptionTrack[];
  transport?: "player" | "android";
};

export type TranslateLine = { id: number; text: string };

export type DebugLogEntry = {
  timestamp: number;
  level: "info" | "warn" | "error" | "success";
  source: "popup" | "content" | "worker";
  message: string;
};

export type RuntimeMessage =
  | { type: "GET_EXTENSION_STATE_V2" }
  | { type: "GET_WORKER_INFO_V2" }
  | { type: "TEST_AI_CONNECTION" }
  | { type: "GET_STORED_STATE"; tabId: number }
  | { type: "DEBUG_LOG"; protocolVersion: 2; entry: DebugLogEntry; tabId?: number }
  | { type: "GET_DEBUG_LOGS"; tabId: number }
  | { type: "CLEAR_DEBUG_LOGS"; tabId: number }
  | { type: "STATE_UPDATED"; protocolVersion: 2; payload: ExtensionState }
  | { type: "UPDATE_SETTINGS"; payload: Partial<SubtitleSettings> }
  | { type: "CLEAR_VIDEO_CACHE" }
  | { type: "CLEAR_ALL_CACHE" }
  | { type: "RETRANSLATE" }
  | { type: "GET_CAPTION_TRACKS"; videoId: string }
  | {
      type: "FETCH_CAPTIONS";
      trackUrl: string;
      videoId: string;
      languageCode: string;
      isAutoGenerated: boolean;
    }
  | {
      type: "TRANSLATE_BATCH_V2";
      runId: string;
      lines: TranslateLine[];
      videoId: string;
      strategy?: "fast-start" | "quality" | "full-video";
    }
  | {
      type: "CACHE_GET";
      videoId: string;
      sourceLanguage: string;
      trackId: string;
    }
  | { type: "CACHE_SET"; cache: TranslationCache }
  | { type: "CACHE_DELETE_VIDEO"; videoId: string }
  | { type: "CACHE_CLEAR_ALL" };

export type WorkerResponse<T> =
  | { ok: true; data: T }
  | { ok: false; error: string };
